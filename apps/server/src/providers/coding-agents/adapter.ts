import type { ProjectProfile } from "../../workspace/project-inspector.js";

export interface AgentExecutionInput {
  projectId: string;
  runId: string;
  taskId: string;
  attemptNumber: number;
  /** 0 for the first dispatch of an iteration; >0 when the same instruction is re-sent after an infrastructure failure. */
  dispatchRetry?: number;
  workspacePath: string;
  taskText: string;
  title: string;
  acceptanceCriteria: string[];
  profile: ProjectProfile;
  /** Files the planner considered relevant (workspace-relative). */
  filesToRead: string[];
  /** Concrete reasons the previous attempt was rejected, including check output. */
  previousFailure?: string;
  guidance?: string[];
  /** Instructions written by the reasoning provider for an external agent (closed-loop mode). */
  instruction?: string;
  signal?: AbortSignal;
  onLog: (line: string) => void;
}

/** What an external agent observably did, read from its own records. */
export interface AgentTranscript {
  conversationId: string | null;
  state: "finished" | "timeout" | "not_started" | "cancelled" | "error";
  finalReply: string;
  toolCalls: Array<{ tool: string; summary: string }>;
  writesOutsideWorkspace: string[];
  prompt: string;
}

export interface AgentExecutionResult {
  status: "completed" | "failed";
  summary: string;
  /** What the mechanism says it wrote. The orchestrator's own diff is the source of truth. */
  filesWritten: string[];
  filesDeleted: string[];
  rejectedWrites: Array<{ path: string; reason: string }>;
  error?: string;
  /**
   * Category of an abrupt agent failure: "quota" (model quota/rate limit exhausted), "agent_error"
   * (the agent stopped on a model or tool error), "timeout", or "not_started".
   */
  errorKind?: "quota" | "agent_error" | "timeout" | "not_started";
  modelId?: string;
  warnings: string[];
  transcript?: AgentTranscript;
}

export interface CodingAgentAvailability {
  available: boolean;
  detail: string;
}

export interface CodingAgentAdapter {
  id: string;
  displayName: string;
  /** One sentence describing what actually happens when this mechanism runs. */
  description: string;
  /** True when file contents are generated by the selected reasoning provider. */
  usesReasoningProvider: boolean;
  detect(): Promise<CodingAgentAvailability>;
  execute(input: AgentExecutionInput): Promise<AgentExecutionResult>;
}
