import type { ProjectProfile } from "../../workspace/project-inspector.js";

export interface AgentExecutionInput {
  projectId: string;
  runId: string;
  taskId: string;
  attemptNumber: number;
  workspacePath: string;
  taskText: string;
  title: string;
  acceptanceCriteria: string[];
  profile: ProjectProfile;
  /** Files the planner considered relevant (workspace-relative). */
  filesToRead: string[];
  /** Concrete reasons the previous attempt was rejected, including check output. */
  previousFailure?: string;
  guidance?: string[];
  signal?: AbortSignal;
  onLog: (line: string) => void;
}

export interface AgentExecutionResult {
  status: "completed" | "failed";
  summary: string;
  /** What the mechanism says it wrote. The orchestrator's own diff is the source of truth. */
  filesWritten: string[];
  filesDeleted: string[];
  rejectedWrites: Array<{ path: string; reason: string }>;
  error?: string;
  modelId?: string;
  warnings: string[];
}

export interface CodingAgentAvailability {
  available: boolean;
  detail: string;
}

export interface CodingAgentAdapter {
  id: string;
  displayName: string;
  /** One sentence describing what actually happens when this mechanism runs. */
  description: string;
  /** True when file contents are generated by the selected reasoning provider. */
  usesReasoningProvider: boolean;
  detect(): Promise<CodingAgentAvailability>;
  execute(input: AgentExecutionInput): Promise<AgentExecutionResult>;
}
